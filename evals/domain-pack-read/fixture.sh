#!/usr/bin/env bash
# 지난 프로젝트에서 쌓인 사용자 단위 업종 팩(~/.riff/domains/)을 새 프로젝트 FRAME이 질문 재료로 쓰는지 본다.
set -euo pipefail
mkdir -p "$HOME/.riff/domains"
cat > "$HOME/.riff/domains/pet-grooming.md" <<'PACK'
# 업종 팩 — 반려견 미용 (사용자 라이브러리, 2개 프로젝트에서 확인)
## 키워드
강아지 미용, 애견 미용, 펫 미용, 미용샵, 반려견
## 물어볼 것 (지난 프로젝트에서 사용자가 가정을 고쳐 준 것)
- [경로] 미용 후 사진을 샵 SNS(인스타그램)에 올려도 되는지 보호자 게시 동의를 받는지
- [정책] 출장(방문) 미용도 하는지, 하면 이동비·이동 시간을 예약에 넣는지
- [돈] 견종·체중 구간별 가격표인지, 털 엉킴이 심하면 추가 요금을 미리 동의받는지
PACK
